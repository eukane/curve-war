/**
 * 시뮬레이션 상수. 제1원칙에 따라 모든 상수에 단위, 근거, 확신도를 적는다.
 * 확신도: "근사" = 현실 범위를 참고한 값, "임시" = 근거 없이 균형을 위해 둔 가정.
 * 같은 내용이 docs/MODEL.md에도 있어야 한다. 바꾸면 양쪽을 같이 고친다.
 */
import { DAYS_PER_YEAR } from "./calendar";

/** 1인 1일 곡물 환산 소비량. 단위: kg/인/일. 근사. (모델에는 곡물 한 종류만 있으므로 곡물 환산값)
 *  출처 확인: Broadberry 외(2010 워킹페이퍼)는 Livi-Bacci(1991)를 인용해 "충분히 먹으려면 1인 1일 평균
 *  2,000kcal"로 보고, 중세 잉글랜드는 텃밭·가금·견과·어류 등이 보태므로 주요 경작물·축산물에서
 *  약 1,500kcal면 생존 수요를 맞춘다고 본다. 이 두 값 사이인 약 1,700kcal를 곡물 환산하면
 *  (곡물 kg당 약 3,400kcal, 일반 영양 상식이며 이번에 출처를 확인하지 않음) 약 0.5kg. */
export const GRAIN_KG_PER_PERSON_DAY = 0.5;

/** 헥타르당 총수확량(평년, 씨앗 포함). 단위: kg/ha. 근사.
 *  출처(2차): 위키백과 "Agriculture in the Middle Ages"는 잉글랜드 1250~1450년 곡물 평균 수확량을
 *  에이커당 7~15부셸(헥타르당 470~1,000kg)로 적는다. 700은 그 범위 안이다.
 *  원자료(Campbell 등의 장원 회계 데이터베이스)는 직접 확인하지 못했다.
 *  이 값은 "실제로 파종한 면적"당 수확량이다. 휴경지는 arableHa에 넣지 않는다. */
export const YIELD_KG_PER_HA = 700;

/** 헥타르당 파종에 드는 종자. 단위: kg/ha. 근사.
 *  확인한 출처: Winchester 주교 장원들의 밀 파종량은 에이커당 2.0~2.5부셸(Schneider 2011 논문 본문).
 *  밀 1부셸을 약 27kg으로 보면(일반 상식, 이번에 출처 미확인) 에이커당 약 54~68kg, 헥타르당 약 135~170kg.
 *  150을 쓴다. 평년 수확량 700과 비교하면 수확 대 파종 비율이 약 4.7:1로, 서식스 장원의 밀 4.34:1
 *  (위키백과, 2차)과 같은 자릿수다. */
export const SEED_KG_PER_HA = 150;

/** 농민 1명이 경작할 수 있는 파종 면적. 단위: ha/인. 임시(약한 근거 있음).
 *  약한 근거: 잉글랜드 장원의 가버게이트(virgate)는 명목상 약 30에이커(24~32에이커 범위),
 *  한 사례 안내서는 가구의 약 20%가 가버게이트, 30%가 그 절반(bovate), 50%가 코터(소농)라고 하나
 *  이 비율은 약한 출처(2차)다. 이를 가중하면 가구당 평균 약 12에이커(약 4.9ha), 3포제로 2/3만 파종하면
 *  약 3.2ha, 5인 가구로 나누면 인당 약 0.65ha. 반올림해 0.7. */
export const HA_PER_FARMER = 0.7;

/** 곡창 연간 손실률(쥐, 습기, 벌레). 단위: 1/년. 임시. */
export const STORAGE_LOSS_PER_YEAR = 0.05;
export const STORAGE_LOSS_PER_DAY = 1 - Math.pow(1 - STORAGE_LOSS_PER_YEAR, 1 / DAYS_PER_YEAR);

/** 수확일. 단위: 연중 일차(0~359). 임시. 가을(180~269일) 후반인 240일차로 둔다. */
export const HARVEST_DAY_OF_YEAR = 240;

/** 평시 출생률. 단위: 명/천 명/년. 임시.
 *  출생·사망률 각각의 출처는 확인하지 못했다. 확인한 것은 순증가율뿐이다:
 *  위키백과 "Demographics of England" 표(Broadberry 외와 Wrigley·Schofield 인용)에서
 *  잉글랜드 인구 증가기의 연 증가율은 1190~1290년 약 +0.57~0.64%, 1541~1600년 +0.77%,
 *  1490~1541년 +0.98%였다. 아래 출생·사망률은 순증가 연 0.6%가 되도록 정한 값이다. */
export const BIRTHS_PER_1000_YEAR = 40;

/** 평시 사망률. 단위: 명/천 명/년. 임시. 위 출생률 설명 참조. 40 - 34 = 연 0.6%. */
export const DEATHS_PER_1000_YEAR = 34;

/** 식량 부족률 1.0(전혀 못 먹음)일 때 추가되는 연간 사망률. 단위: 1/년. 임시.
 *  검증 목표(2차 출처): 위 위키백과 표에서 잉글랜드 인구는 1315년 4.69백만 → 1325년 4.12백만(약 -12%).
 *  1315~17년 대기근을 포함한 10년이다. 이 모델에서 2년 연속 대흉작이 비슷한 규모(대략 5~25%)의
 *  인구 감소를 내는지를 world.test.ts가 확인한다. 선형으로 단순화했다. */
export const STARVATION_DEATH_RATE_AT_FULL_DEFICIT = 0.15;

/** 식량 부족률 1.0일 때 출생이 줄어드는 비율의 기울기. 단위: 무차원. 임시.
 *  부족률 0.67 이상이면 출생이 0이 된다. */
export const BIRTH_SUPPRESSION_PER_DEFICIT = 1.5;

/** 평년 대비 기상 계수의 분산(로그정규 sigma). 단위: 무차원. 임시. 평균은 1이 되도록 보정한다.
 *  Broadberry 외는 "단기 변동성이 매우 크다"고만 적었고 수치를 확인하지 못했다. */
export const WEATHER_SIGMA = 0.18;
/** 최저 기상 계수. 근사. 위키백과는 흉년에 에이커당 4부셸 미만(평균 7~15의 중간값 약 11 대비 0.36 이하)을
 *  든다. 0.4로 둔다. */
export const WEATHER_MIN = 0.4;
export const WEATHER_MAX = 1.35;

/** 파종일. 단위: 연중 일차. 임시. 봄(0~89일)의 중간. */
export const SOWING_DAY_OF_YEAR = 60;

/** 파종 점검일(이벤트 발생 시점). 단위: 연중 일차. 임시. 파종 15일 전. */
export const SPRING_CHECK_DAY_OF_YEAR = 45;

/** 수확 직전 점검일(이벤트 발생 시점). 단위: 연중 일차. 임시. 수확 15일 전. */
export const HARVEST_ALERT_DAY_OF_YEAR = HARVEST_DAY_OF_YEAR - 15;

/** 개간(숲·황무지를 경작지로 만드는 일)에 드는 노동. 단위: 인·일/ha. 임시. **출처를 찾지 못했다.**
 *  확인한 것은 정성적 서술뿐이다: 개간은 노동집약적이고 오래 걸리는 일이며, 불을 놓아 덤불을 치우고
 *  그루터기를 뽑는 작업을 포함한다(위키백과 "Assarting"). 결과가 이 값에 민감하므로 근거 확보가 필요하다. */
export const CLEARING_LABOR_DAYS_PER_HA = 150;

/** 새로 개간한 땅의 지력. 단위: 배. 임시. 처음부터 좋은 땅이 먼저 개간되었다고 보고 평균보다 낮게 둔다.
 *  (수확 체감은 Broadberry 외가 맬서스 모형의 전제로 언급하지만, 이 수치 자체는 근거 없음) */
export const SOIL_OF_CLEARED_LAND = 0.85;
